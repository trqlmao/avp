/**
 * Build llms-full.txt: a single-file, full-text bundle of the human-facing AVP docs for AI ingestion
 * (the llmstxt.org "full" variant, sibling to llms.txt). It concatenates the implementer guide, the
 * normative specification, and the threat model verbatim, with a source marker before each.
 *
 *   node scripts/build-llms-full.mjs --check   (default) assert llms-full.txt is in sync; exit 1 on drift
 *   node scripts/build-llms-full.mjs --write    regenerate llms-full.txt
 *
 * Run --check in CI so the bundle can never rot relative to its sources.
 *
 * SPDX-License-Identifier: MIT
 */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

// Reading order mirrors how a human is told to read them: guide, then normative detail, then security.
const SOURCES = ["IMPLEMENTING.md", "SPEC.md", "THREATMODEL.md"];
const OUT = "llms-full.txt";

const HEADER = `# AVP (Alt Vault Protocol): full text

> Single-file bundle of the human-facing AVP docs for AI ingestion: the implementer guide, the normative
> specification, and the threat model, concatenated verbatim. Machine-readable artifacts (proto, JSON
> Schema, OpenAPI, conformance vectors) and the structured index are linked from llms.txt. Generated by
> scripts/build-llms-full.mjs; do not edit by hand.
`;

const rule = "=".repeat(80);

function build() {
  let out = HEADER;
  for (const file of SOURCES) {
    const body = readFileSync(join(root, file), "utf8").replace(/\n+$/, "");
    out += `\n\n${rule}\nSource: ${file}\n${rule}\n\n${body}\n`;
  }
  return out;
}

const generated = build();
const write = process.argv.includes("--write");

if (write) {
  writeFileSync(join(root, OUT), generated);
  console.log(`Wrote ${OUT} (${generated.length} bytes) from ${SOURCES.join(", ")}.`);
} else {
  let committed = "";
  try {
    committed = readFileSync(join(root, OUT), "utf8");
  } catch {
    committed = "";
  }
  if (committed !== generated) {
    console.error(`${OUT} is out of sync with ${SOURCES.join(", ")}. Run: node scripts/build-llms-full.mjs --write`);
    process.exitCode = 1;
  } else {
    console.log(`${OUT} is in sync with ${SOURCES.join(", ")}.`);
  }
}
